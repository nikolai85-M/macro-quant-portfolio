def get_sector(ticker):
    """Возвращает сектор для тикера"""
    if ticker in EXCLUDED_TICKERS:
        return 'Исключено'
    return SECTOR_MAP.get(ticker, 'Прочее')

def get_all_sectors():
    """Возвращает список всех уникальных секторов"""
    return list(set(SECTOR_MAP.values()))

def get_tickers_by_sector(sector):
    """Возвращает список тикеров в указанном секторе"""
    return [ticker for ticker, s in SECTOR_MAP.items() if s == sector]